func TestTrackingWriterClassification(t *testing.T) {
	pristine := []byte("hello   world")
	working := make([]byte, len(pristine), len(pristine)+1)
	copy(working, pristine)

	var out bytes.Buffer
	tw := newTrackingWriter(&out, working, pristine)

	// Verbatim pass-through of "hello".
	_, err := tw.Write(working[0:5])
	test.Error(t, err)

	// In-place whitespace collapse (like parse.ReplaceMultipleWhitespace).
	// The returned subslice often sits over the surviving characters and can
	// still verify exact against pristine at its recovered offset.
	collapsed := parse.ReplaceMultipleWhitespace(working[5:])
	_, err = tw.Write(collapsed)
	test.Error(t, err)

	// Synthesized literal.
	_, err = tw.Write([]byte(";"))
	test.Error(t, err)

	ix := tw.finish(len(pristine))
	test.That(t, len(ix.segs) >= 2)

	// First "hello" is exact slope-1.
	loc, exact, err := ix.Original(0)
	test.Error(t, err)
	test.That(t, exact)
	test.T(t, loc.Offset, 0)

	loc, exact, err = ix.Original(4)
	test.Error(t, err)
	test.That(t, exact)
	test.T(t, loc.Offset, 4)

	// After collapse, generated " world" maps exactly onto pristine[7:13].
	loc, exact, err = ix.Original(5)
	test.Error(t, err)
	test.That(t, exact)
	test.T(t, loc.Offset, 7)

	// Synthesized ";" inherits last original byte of previous write.
	semiGen := ix.outLen - 1
	loc, exact, err = ix.Original(semiGen)
	test.Error(t, err)
	test.That(t, !exact)
	test.T(t, loc.Offset, 12)
}

func TestTrackingWriterSynthesizedExactExtension(t *testing.T) {
	// After an exact run, a synthesized buffer that continues the pristine
	// stream byte-for-byte must extend the exact segment (coverage win).
	pristine := []byte("hello world!")
	working := make([]byte, len(pristine), len(pristine)+1)
	copy(working, pristine)

	var out bytes.Buffer
	tw := newTrackingWriter(&out, working, pristine)

	// Exact pass-through of "hello ".
	_, err := tw.Write(working[0:6])
	test.Error(t, err)

	// Synthesized copy of "world" (new allocation, not a subslice of working).
	syn := append([]byte(nil), pristine[6:11]...)
	_, err = tw.Write(syn)
	test.Error(t, err)

	// Synthesized "!" then junk that does not match pristine.
	_, err = tw.Write([]byte("!?"))
	test.Error(t, err)

	ix := tw.finish(len(pristine))
	// "hello world!" should be exact; trailing "?" non-exact.
	for g := 0; g < len("hello world!"); g++ {
		loc, exact, err := ix.Original(g)
		test.Error(t, err)
		test.That(t, exact)
		test.T(t, loc.Offset, g)
		test.T(t, out.Bytes()[g], pristine[g])
	}
	loc, exact, err := ix.Original(len("hello world!"))
	test.Error(t, err)
	test.That(t, !exact)
	_ = loc
	// 12 of 13 generated bytes exact.
	test.That(t, ix.Coverage() > 0.9)
}

func TestTrackingWriterWhitespaceCollapseMultiline(t *testing.T) {
	// HTML text token spanning two source lines: "\n\t" collapsed to "\n".
	// Second line must map to its own source line, not the token start.
	pristine := []byte("<p>hello,\n\tworld</p>")
	working := make([]byte, len(pristine), len(pristine)+1)
	copy(working, pristine)
	var out bytes.Buffer
	tw := newTrackingWriter(&out, working, pristine)

	// <p>
	_, err := tw.Write(working[0:3])
	test.Error(t, err)
	// Text with collapse of "\n\t" → "\n" (same as parse.ReplaceMultipleWhitespace).
	text := working[3 : len(working)-4] // "hello,\n\tworld"
	collapsed := parse.ReplaceMultipleWhitespace(text)
	test.Bytes(t, collapsed, []byte("hello,\nworld"))
	_, err = tw.Write(collapsed)
	test.Error(t, err)
	// </p>
	_, err = tw.Write(working[len(working)-4:])
	test.Error(t, err)

	ix := tw.finish(len(pristine))
	minified := out.Bytes()
	// "world" in output
	wi := bytes.Index(minified, []byte("world"))
	test.That(t, wi >= 0)
	loc, exact, err := ix.Original(wi)
	test.Error(t, err)
	test.That(t, exact)
	// Original "world" starts after "\n\t"
	want := bytes.Index(pristine, []byte("world"))
	test.T(t, loc.Offset, want)
	test.T(t, loc.Line, 2)
}

