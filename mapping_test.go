func TestNoteGenLinesCRLFSplitAcrossWrites(t *testing.T) {
	// "\r\n" must be one newline even when the two bytes arrive in separate Writes.
	pristine := []byte("a\r\nb")
	working := make([]byte, len(pristine), len(pristine)+1)
	copy(working, pristine)

	var out bytes.Buffer
	tw := newTrackingWriter(&out, working, pristine)
	_, err := tw.Write([]byte("a\r"))
	test.Error(t, err)
	_, err = tw.Write([]byte("\nb"))
	test.Error(t, err)

	ix := tw.finish(len(pristine))
	want := lineStarts(out.Bytes())
	test.T(t, ix.genLines, want)
	test.T(t, want, []int{0, 3})

	// Bare CR then non-LF must not adjust the previous line start.
	out.Reset()
	tw = newTrackingWriter(&out, working, []byte("a\rb"))
	_, err = tw.Write([]byte("a\r"))
	test.Error(t, err)
	_, err = tw.Write([]byte("b"))
	test.Error(t, err)
	ix = tw.finish(3)
	test.T(t, ix.genLines, lineStarts(out.Bytes()))
	test.T(t, ix.genLines, []int{0, 2})
}

