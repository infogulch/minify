// writeReaderBytes writes r's underlying slice when available so the tracking
// writer can see true input subslices (io.Copy always synthesizes).
func writeReaderBytes(w io.Writer, r io.Reader) error {
	if b, ok := r.(interface{ Bytes() []byte }); ok {
		_, err := w.Write(b.Bytes())
		return err
	}
	_, err := io.Copy(w, r)
	return err
}

