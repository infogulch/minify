// --- segment audit (test-only) ---

// SegmentAudit is a diagnostic report from auditing an Index.
// Test-only (this file); not part of the public library API.
//
// GenIssues are structural failures (generated coverage wrong → lookup broken).
// ExactOverlaps are exact segments whose original range intersects a previously
// claimed exact original range — multi-emit of the same working subslice (e.g.
// JS Var.Data written at every use, all mapping “exact” to the binding). That is
// a correctness bug: byte-equality still holds, so coverage stays high while
// occurrence identity is wrong.
//
// Out-of-order first claims (orig jumps backward into an unclaimed gap) are
// recorded in ExactOutOfOrder for investigation but are not counted as overlaps.
type SegmentAudit struct {
	GenIssues       int
	ExactOverlaps   int
	ExactOverlapB   int // generated bytes in overlapping exact segments
	ExactOutOfOrder int // first-time exact claims with orig < prior high-water (no overlap)
	ExactSegments   int
	ExactBytes      int
	NonExactBytes   int
	SegCount        int
	Report          string
}

// AuditSegments scans the segment list for:
//  1. Generated-space structure: contiguous coverage of [0, outLen), no gaps/overlaps.
//  2. Exact original claims: overlapping ranges (multi-emit) vs mere out-of-order.
//
// pristine and minified are optional but enable context snippets in Report.
// Defined in a test file so package minify and package minify_test can use it
// during `go test` without exporting audit machinery from the library API.
func (ix *Index) AuditSegments(pristine, minified []byte) SegmentAudit {
	var a SegmentAudit
	if ix == nil {
		a.GenIssues = 1
		a.Report = "nil Index\n"
		return a
	}
	a.SegCount = len(ix.segs)

	var b strings.Builder
	fmt.Fprintf(&b, "audit: outLen=%d srcLen=%d segs=%d coverage=%.4f\n",
		ix.outLen, ix.srcLen, len(ix.segs), ix.coverage())

	// --- generated contiguity ---
	expectGen := 0
	for i, s := range ix.segs {
		if s.length <= 0 {
			a.GenIssues++
			fmt.Fprintf(&b, "GEN  seg[%d] non-positive length=%d gen=%d orig=%d exact=%v\n",
				i, s.length, s.gen, s.orig, s.exact)
		}
		if s.gen != expectGen {
			a.GenIssues++
			fmt.Fprintf(&b, "GEN  seg[%d] gen=%d want %d (gap/overlap) length=%d orig=%d exact=%v\n",
				i, s.gen, expectGen, s.length, s.orig, s.exact)
			writeSegContext(&b, "     ", s, pristine, minified)
		}
		if s.exact {
			a.ExactSegments++
			a.ExactBytes += s.length
			if s.orig < 0 || (s.length > 0 && s.orig+s.length > ix.srcLen) || (s.length == 0 && s.orig > ix.srcLen) {
				a.GenIssues++
				fmt.Fprintf(&b, "GEN  seg[%d] exact orig range [%d,%d) outside srcLen=%d\n",
					i, s.orig, s.orig+s.length, ix.srcLen)
				writeSegContext(&b, "     ", s, pristine, minified)
			}
		} else {
			a.NonExactBytes += s.length
			if s.orig < 0 || (ix.srcLen > 0 && s.orig > ix.srcLen) || (ix.srcLen == 0 && s.orig != 0) {
				a.GenIssues++
				fmt.Fprintf(&b, "GEN  seg[%d] non-exact orig=%d outside srcLen=%d\n", i, s.orig, ix.srcLen)
			}
		}
		expectGen = s.gen + s.length
	}
	if expectGen != ix.outLen {
		a.GenIssues++
		fmt.Fprintf(&b, "GEN  segments cover gen [0,%d) but outLen=%d\n", expectGen, ix.outLen)
	}
	if len(ix.segs) == 0 && ix.outLen != 0 {
		a.GenIssues++
		fmt.Fprintf(&b, "GEN  empty segment list but outLen=%d\n", ix.outLen)
	}

	// --- exact original ranges: overlap (multi-emit) vs out-of-order ---
	// Track claimed [start,end) intervals merged and sorted. Overlap ⇒ multi-emit.
	// orig < highWater without overlap ⇒ out-of-order first claim (logged, not fatal).
	var claimed []origInterval
	highWater := 0
	const maxOverlapPrint = 20
	overlapPrinted := 0
	for i := range ix.segs {
		s := &ix.segs[i]
		if !s.exact || s.length <= 0 {
			continue
		}
		o, end := s.orig, s.orig+s.length
		if hit, prev := findOrigOverlap(claimed, o, end); hit {
			a.ExactOverlaps++
			a.ExactOverlapB += s.length
			if overlapPrinted < maxOverlapPrint {
				overlapPrinted++
				fmt.Fprintf(&b, "EXACT-OVERLAP seg[%d] gen=[%d,%d) orig=[%d,%d) intersects claimed [%d,%d)\n",
					i, s.gen, s.gen+s.length, o, end, prev.start, prev.end)
				writeSegContext(&b, "     this  ", *s, pristine, minified)
				if pristine != nil {
					// intersection
					is, ie := o, end
					if prev.start > is {
						is = prev.start
					}
					if prev.end < ie {
						ie = prev.end
					}
					if ie > is {
						fmt.Fprintf(&b, "     pristine intersect [%d,%d): %q\n",
							is, ie, snippet(pristine, is, ie-is))
					}
				}
			}
		} else if o < highWater {
			a.ExactOutOfOrder++
			// Not an overlap: first claim of this range, but emission order went
			// backward into a gap. Useful signal; not treated as multi-emit.
		}
		claimed = addOrigInterval(claimed, o, end)
		if end > highWater {
			highWater = end
		}
	}
	if a.ExactOverlaps > maxOverlapPrint {
		fmt.Fprintf(&b, "EXACT-OVERLAP ... %d more overlap(s) not printed\n", a.ExactOverlaps-maxOverlapPrint)
	}

	if a.GenIssues == 0 && a.ExactOverlaps == 0 {
		fmt.Fprintf(&b, "OK  gen contiguous; no exact orig overlaps (outOfOrder=%d highWater=%d claimedIntervals=%d)\n",
			a.ExactOutOfOrder, highWater, len(claimed))
	} else {
		fmt.Fprintf(&b, "SUMMARY genIssues=%d exactOverlaps=%d exactOverlapBytes=%d exactOutOfOrder=%d exactBytes=%d nonExactBytes=%d\n",
			a.GenIssues, a.ExactOverlaps, a.ExactOverlapB, a.ExactOutOfOrder, a.ExactBytes, a.NonExactBytes)
	}
	a.Report = b.String()
	return a
}

func writeSegContext(b *strings.Builder, prefix string, s segment, pristine, minified []byte) {
	const win = 32
	if minified != nil && s.gen >= 0 && s.gen < len(minified) {
		n := s.length
		if n > win {
			n = win
		}
		fmt.Fprintf(b, "%sminified[%d:]=%q\n", prefix, s.gen, snippet(minified, s.gen, n))
	}
	if pristine != nil && s.orig >= 0 && s.orig < len(pristine) {
		n := s.length
		if !s.exact {
			n = win
		} else if n > win {
			n = win
		}
		fmt.Fprintf(b, "%spristine[%d:]=%q\n", prefix, s.orig, snippet(pristine, s.orig, n))
	}
}

func snippet(b []byte, off, n int) string {
	if b == nil || off < 0 || off >= len(b) || n <= 0 {
		return ""
	}
	end := off + n
	if end > len(b) {
		end = len(b)
	}
	s := make([]byte, 0, end-off)
	for _, c := range b[off:end] {
		switch c {
		case '\n':
			s = append(s, '\\', 'n')
		case '\r':
			s = append(s, '\\', 'r')
		case '\t':
			s = append(s, '\\', 't')
		default:
			s = append(s, c)
		}
	}
	return string(s)
}
