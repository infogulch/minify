// Coverage re-exports coverage for tests (including package minify_test).
// Not part of the stable library API.
func (ix *Index) Coverage() float64 { return ix.coverage() }

// reportAudit logs the audit report and fails on gen structural issues.
// Exact overlaps are reported loudly; failExact makes them a test failure
// (correctness: exact multi-emit is wrong even when byte-equality holds).
func reportAudit(t *testing.T, name string, a SegmentAudit, failExact bool) {
	t.Helper()
	if a.Report != "" {
		t.Log("\n" + a.Report)
	}
	if a.GenIssues > 0 {
		t.Errorf("%s: %d generated-space structural issue(s)", name, a.GenIssues)
	}
	if a.ExactOverlaps > 0 {
		msg := fmt.Sprintf("%s: %d exact orig overlap(s) covering %d generated bytes (multi-emit)",
			name, a.ExactOverlaps, a.ExactOverlapB)
		if failExact {
			t.Error(msg)
		} else {
			t.Log(msg)
		}
	}
	if a.ExactOutOfOrder > 0 {
		t.Logf("%s: %d out-of-order exact first-claims (no overlap; informational)", name, a.ExactOutOfOrder)
	}
}

