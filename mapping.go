// lineStarts returns byte offsets of each line start, matching parse.Position
// newline rules: \n, \r, \r\n, U+2028, U+2029.
func lineStarts(src []byte) []int {
	starts := make([]int, 1, 8)
	starts[0] = 0
	for i := 0; i < len(src); {
		c := src[i]
		n := 1
		newline := false
		if c == '\n' {
			newline = true
		} else if c == '\r' {
			newline = true
			if i+1 < len(src) && src[i+1] == '\n' {
				n = 2
			}
		} else if c >= 0xC0 {
			r, size := utf8.DecodeRune(src[i:])
			if size > 1 && (r == '\u2028' || r == '\u2029') {
				newline = true
				n = size
			} else if size > 1 {
				n = size
			}
		}
		i += n
		if newline {
			starts = append(starts, i)
		}
	}
	return starts
}

func locationAt(lineStarts []int, offset int) Location {
	if offset < 0 {
		offset = 0
	}
	// Empty table (zero-value Index, or missing lineStarts): treat as one line at 0.
	if len(lineStarts) == 0 {
		return Location{Offset: offset, Line: 1, LinePos: offset + 1}
	}
	// Largest lineStarts[i] <= offset.
	i := sort.Search(len(lineStarts), func(j int) bool {
		return lineStarts[j] > offset
	}) - 1
	if i < 0 {
		i = 0
	}
	start := lineStarts[i]
	return Location{
		Offset:  offset,
		Line:    i + 1,
		LinePos: offset - start + 1,
	}
}

func positionToOffset(lineStarts []int, totalLen, line, col int) (int, error) {
	if line < 1 || col < 1 || len(lineStarts) == 0 {
		return 0, ErrOutOfRange
	}
	if line > len(lineStarts) {
		return 0, ErrOutOfRange
	}
	start := lineStarts[line-1]
	off := start + col - 1
	// Allow one-past end of this line (or file): start <= off <= lineEnd.
	var lineEnd int
	if line < len(lineStarts) {
		lineEnd = lineStarts[line]
	} else {
		lineEnd = totalLen
	}
	if off < start || off > lineEnd || off > totalLen {
		return 0, ErrOutOfRange
	}
	return off, nil
}
