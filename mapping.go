// MinifyMapped minifies input and builds a mapping Index from generated offsets
// back to the original source. The caller's input slice is not mutated.
//
// It copies input into a working buffer so minifiers may rewrite tokens in place
// while a pristine view is kept for line-starts and exactness checks.
func (m *M) MinifyMapped(mediatype string, w io.Writer, input []byte) (*Index, error) {
	return m.minifyMapped(mediatype, w, input)
}

// BytesMapped minifies v and returns the minified bytes plus a mapping Index.
// The caller's v is not mutated. On error it returns the original v, a nil Index,
// and the error (same slice-on-error pattern as Bytes). Use MinifyMapped when you
// need the Index of a partial write on failure.
func (m *M) BytesMapped(mediatype string, v []byte) ([]byte, *Index, error) {
	out := buffer.NewWriter(make([]byte, 0, len(v)))
	ix, err := m.minifyMapped(mediatype, out, v)
	if err != nil {
		return v, nil, err
	}
	return out.Bytes(), ix, nil
}

func (m *M) minifyMapped(mediatype string, w io.Writer, input []byte) (*Index, error) {
	// Working copy: spare byte for parse.NewInputBytes NULL terminator without realloc.
	working := make([]byte, len(input), len(input)+1)
	copy(working, input)

	tw := newTrackingWriter(w, working, input)
	err := m.Minify(mediatype, tw, buffer.NewReader(working))
	ix := tw.finish(len(input))
	return ix, err
}

