// ErrOutOfRange is returned when a generated position is outside the minified output.
var ErrOutOfRange = errors.New("generated position out of range")

// Location is a position in the original (unminified) source.
// Line and LinePos are 1-based. LinePos is a byte column within the line
// (matching go/token.Position), not a rune or UTF-16 column.
type Location struct {
	Offset  int // byte offset into original source
	Line    int // 1-based
	LinePos int // 1-based, byte-based column within the line
}

// Index maps generated (minified) byte offsets back to original source positions.
// It retains only the segment list, line-start arrays, and output length — not
// the original or minified text. After MinifyMapped/BytesMapped returns, Index is
// immutable and its public API is safe for concurrent use.
//
// Segments are exact (slope-1 pass-through equal to pristine) or non-exact (whole
// run maps to one original offset). Attribute-embedded JS/CSS often maps only to
// the attribute start; TemplateDelims tokens usually stay exact.
type Index struct {
	segs      []segment
	origLines []int // byte offsets of line starts in original
	genLines  []int // byte offsets of line starts in generated
	outLen    int
	srcLen    int // original source length (for end-of-source mapping)
}

// segment is a maximal run of generated bytes sharing one mapping rule.
type segment struct {
	gen    int  // start offset in generated output
	orig   int  // original offset (start of slope-1 run, or point target)
	length int  // length in generated space
	exact  bool // true → slope-1; false → all bytes map to orig
}

// coverage returns the fraction of generated bytes that are exactly mapped.
// Test-only surface; re-exported as Coverage from mapping_test.go.
func (ix *Index) coverage() float64 {
	if ix == nil || ix.outLen == 0 {
		return 0
	}
	exact := 0
	for i := range ix.segs {
		if ix.segs[i].exact {
			exact += ix.segs[i].length
		}
	}
	return float64(exact) / float64(ix.outLen)
}

// Original maps a generated byte offset to an original Location.
// gen may be equal to the output length (one-past-the-end, e.g. unexpected EOF).
// exact is true only for slope-1 pass-through segments with gen < outLen
// (there is a generated byte to compare). At gen == outLen, exact is always false.
func (ix *Index) Original(gen int) (loc Location, exact bool, err error) {
	if ix == nil || gen < 0 || gen > ix.outLen {
		return Location{}, false, ErrOutOfRange
	}
	if ix.outLen == 0 {
		return locationAt(ix.origLines, 0), false, nil
	}
	if gen == ix.outLen {
		return ix.endLocation()
	}
	seg := ix.segmentAt(gen)
	if seg.exact {
		off := seg.orig + (gen - seg.gen)
		return locationAt(ix.origLines, off), true, nil
	}
	return locationAt(ix.origLines, seg.orig), false, nil
}

// OriginalForPosition maps a 1-based line and byte column in the *minified*
// output to an original Location. The caller need not re-supply the minified text.
func (ix *Index) OriginalForPosition(line, col int) (loc Location, exact bool, err error) {
	if ix == nil {
		return Location{}, false, ErrOutOfRange
	}
	gen, err := positionToOffset(ix.genLines, ix.outLen, line, col)
	if err != nil {
		return Location{}, false, err
	}
	return ix.Original(gen)
}

func (ix *Index) endLocation() (Location, bool, error) {
	if len(ix.segs) == 0 {
		return locationAt(ix.origLines, ix.srcLen), false, nil
	}
	last := ix.segs[len(ix.segs)-1]
	off := last.orig
	if last.exact {
		off = last.orig + last.length
		if off > ix.srcLen {
			off = ix.srcLen
		}
	}
	// One-past-the-end: no generated byte to compare, so exact is always false.
	return locationAt(ix.origLines, off), false, nil
}

func (ix *Index) segmentAt(gen int) segment {
	// segs cover [0, outLen) contiguously when non-empty.
	if len(ix.segs) == 0 {
		return segment{}
	}
	i := sort.Search(len(ix.segs), func(i int) bool {
		return ix.segs[i].gen+ix.segs[i].length > gen
	})
	if i >= len(ix.segs) {
		return ix.segs[len(ix.segs)-1]
	}
	return ix.segs[i]
}

