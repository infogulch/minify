// Not safe for concurrent use.
type trackingWriter struct {
	w        io.Writer
	working  []byte // minifier mutates this; used for subslice offset recovery
	pristine []byte // immutable original; used for exactness and line-starts
	segs     []segment
	genPos   int
	genLines []int
	lastOrig int
	hasLast  bool
	// lastWasCR is true when the previous Write ended with a lone '\r' that
	// was recorded as a newline. If the next Write starts with '\n', that
	// completes a CRLF and must not open a second line.
	lastWasCR bool
	// claimed tracks pristine [start,end) ranges already used by an exact segment.
	// A second write of the same working subslice (e.g. JS Var.Data at every use)
	// must not be marked exact again — occurrence identity would be wrong even
	// though byte-equality still holds.
	claimed []origInterval
}

func newTrackingWriter(w io.Writer, working, pristine []byte) *trackingWriter {
	return &trackingWriter{
		w:        w,
		working:  working,
		pristine: pristine,
		genLines: []int{0},
	}
}

func (t *trackingWriter) Write(b []byte) (int, error) {
	n, err := t.w.Write(b)
	if n > 0 {
		t.record(b[:n])
		t.noteGenLines(b[:n])
		t.genPos += n
	}
	return n, err
}

func (t *trackingWriter) finish(srcLen int) *Index {
	return &Index{
		segs:      t.segs,
		origLines: lineStarts(t.pristine),
		genLines:  t.genLines,
		outLen:    t.genPos,
		srcLen:    srcLen,
	}
}

func (t *trackingWriter) record(b []byte) {
	gen := t.genPos
	if off, ok := offsetIn(t.working, b); ok {
		if off+len(b) <= len(t.pristine) && bytes.Equal(b, t.pristine[off:off+len(b)]) {
			if t.claimExact(gen, off, len(b)) {
				return
			}
			// Multi-emit of an already-claimed original range (shared AST slice).
			// Map non-exact to the recovered slice offset (typically the binding).
			t.recordNonExact(gen, off, len(b))
			return
		}
		// Subslice of working but bytes differ from pristine: rewritten in place
		// (whitespace collapse, entity decode, number minify, …). Align b against
		// pristine at off, skipping pristine whitespace that was deleted.
		t.recordAligned(gen, b, off)
		return
	}
	// Synthesized (scratch buffer, AST keyword literals, inserted punctuation, …).
	// Exact-cursor prefix match only: content must equal pristine contiguously
	// after the last exact segment. No whole-buffer search — that mis-attributed
	// common substrings (e.g. minified CSS → random HTML text nodes).
	if n := t.exactPrefixLen(b); n > 0 {
		expect, _ := t.exactCursor()
		// Point-map the unmatched tail at the first pristine byte not covered
		// (not the token start, and not the last matched byte).
		restOrig := expect + n
		if restOrig >= len(t.pristine) {
			restOrig = len(t.pristine) - 1
		}
		if restOrig < 0 {
			restOrig = 0
		}
		t.recordExactThenRest(gen, b, n, restOrig)
		return
	}
	orig := 0
	if t.hasLast {
		orig = t.lastOrig
	}
	t.recordNonExact(gen, orig, len(b))
}

// recordAligned maps a rewritten working subslice by aligning through deleted
// whitespace so collapsed multi-line text keeps source line identity (no free
// substring search).
func (t *trackingWriter) recordAligned(gen int, b []byte, off int) {
	if len(b) == 0 {
		return
	}
	if off < 0 {
		off = 0
	}
	pi := off
	bi := 0
	for bi < len(b) {
		// Longest equal run at (bi, pi).
		n := 0
		for bi+n < len(b) && pi+n < len(t.pristine) && b[bi+n] == t.pristine[pi+n] {
			if hit, _ := findOrigOverlap(t.claimed, pi+n, pi+n+1); hit {
				break
			}
			n++
		}
		if n > 0 {
			if !t.claimExact(gen+bi, pi, n) {
				// Range was claimed between the check and claim; fall through.
				t.recordNonExact(gen+bi, pi, len(b)-bi)
				return
			}
			bi += n
			pi += n
			continue
		}
		// Skip pristine whitespace deleted by collapse (e.g. tab after newline).
		if pi < len(t.pristine) && isMapWhitespace(t.pristine[pi]) {
			// Do not skip if the next output byte is this same whitespace —
			// that byte still needs to map (single kept space/newline).
			if bi < len(b) && b[bi] == t.pristine[pi] {
				// Equal but claimed (overlap break above) — non-exact remainder.
				t.recordNonExact(gen+bi, pi, len(b)-bi)
				return
			}
			pi++
			continue
		}
		// True rewrite (entity, number, etc.): non-exact for the rest.
		restOrig := pi
		if restOrig >= len(t.pristine) {
			restOrig = len(t.pristine) - 1
		}
		if restOrig < 0 {
			restOrig = 0
		}
		t.recordNonExact(gen+bi, restOrig, len(b)-bi)
		return
	}
}

func isMapWhitespace(c byte) bool {
	// Align with parse.IsWhitespace: space, \t, \n, \r, \f.
	return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f'
}

// claimExact records an exact slope-1 segment for pristine[orig:orig+length]
// if that range has not already been claimed. Returns false on multi-emit.
func (t *trackingWriter) claimExact(gen, orig, length int) bool {
	if length <= 0 || orig < 0 || orig+length > len(t.pristine) {
		return false
	}
	end := orig + length
	if hit, _ := findOrigOverlap(t.claimed, orig, end); hit {
		return false
	}
	t.appendSeg(gen, orig, length, true)
	t.claimed = addOrigInterval(t.claimed, orig, end)
	t.lastOrig = end - 1
	t.hasLast = true
	return true
}

func (t *trackingWriter) recordNonExact(gen, orig, length int) {
	if length <= 0 {
		return
	}
	t.appendSeg(gen, orig, length, false)
	t.lastOrig = orig
	t.hasLast = true
}

// exactCursor returns the pristine offset immediately after the last exact
// segment. When there are no segments yet, the cursor is 0 (start of source).
// When the last segment is non-exact there is no reliable contiguous cursor.
func (t *trackingWriter) exactCursor() (expect int, ok bool) {
	if n := len(t.segs); n > 0 {
		last := t.segs[n-1]
		if !last.exact {
			return 0, false
		}
		return last.orig + last.length, true
	}
	return 0, true
}

// exactPrefixLen is the longest N such that b[:N] equals pristine at the exact
// cursor and those pristine bytes are not already claimed exact.
func (t *trackingWriter) exactPrefixLen(b []byte) int {
	expect, ok := t.exactCursor()
	if !ok || expect < 0 || expect > len(t.pristine) {
		return 0
	}
	max := len(b)
	if rem := len(t.pristine) - expect; rem < max {
		max = rem
	}
	n := 0
	for n < max && b[n] == t.pristine[expect+n] {
		if hit, _ := findOrigOverlap(t.claimed, expect+n, expect+n+1); hit {
			break
		}
		n++
	}
	return n
}

// recordExactThenRest records b[:n] as exact at the current exact cursor, then
// the remainder as non-exact point-mapped to restOrig.
func (t *trackingWriter) recordExactThenRest(gen int, b []byte, n, restOrig int) {
	expect, _ := t.exactCursor()
	if !t.claimExact(gen, expect, n) {
		t.recordNonExact(gen, restOrig, len(b))
		return
	}
	if n < len(b) {
		t.appendSeg(gen+n, restOrig, len(b)-n, false)
		t.lastOrig = restOrig
		t.hasLast = true
	}
}

func (t *trackingWriter) appendSeg(gen, orig, length int, exact bool) {
	if length == 0 {
		return
	}
	if n := len(t.segs); n > 0 {
		last := &t.segs[n-1]
		if last.exact == exact && last.gen+last.length == gen {
			if exact && last.orig+last.length == orig {
				last.length += length
				return
			}
			if !exact && last.orig == orig {
				last.length += length
				return
			}
		}
	}
	t.segs = append(t.segs, segment{gen: gen, orig: orig, length: length, exact: exact})
}

func (t *trackingWriter) noteGenLines(b []byte) {
	// Must match lineStarts. lastWasCR stitches CRLF across Writes; multi-byte
	// separators (U+2028/U+2029) are not re-stitched across Writes.
	base := t.genPos
	i := 0
	if t.lastWasCR {
		t.lastWasCR = false
		if len(b) > 0 && b[0] == '\n' {
			// Complete CRLF started in a previous write: the line start was
			// recorded after '\r'; move it past the '\n'.
			if n := len(t.genLines); n > 0 {
				t.genLines[n-1] = base + 1
			}
			i = 1
		}
	}
	for i < len(b) {
		c := b[i]
		n := 1
		newline := false
		if c == '\n' {
			newline = true
		} else if c == '\r' {
			newline = true
			if i+1 < len(b) && b[i+1] == '\n' {
				n = 2
			}
		} else if c >= 0xC0 {
			r, size := utf8.DecodeRune(b[i:])
			if size > 1 && (r == '\u2028' || r == '\u2029') {
				newline = true
				n = size
			} else if size > 1 {
				n = size
			}
		}
		i += n
		if newline {
			t.genLines = append(t.genLines, base+i)
		}
	}
	if len(b) > 0 {
		// Lone trailing '\r' may complete as CRLF on the next Write.
		// A completed "\r\n" ends with '\n', so lastWasCR stays false.
		t.lastWasCR = b[len(b)-1] == '\r'
	}
}

// offsetIn reports whether b is a subslice of buf and returns the byte offset.
// Empty b is never a subslice. Address arithmetic is within one allocation only
// and never converted back to a pointer; exact claims still require pristine equality.
func offsetIn(buf, b []byte) (int, bool) {
	if len(b) == 0 || len(buf) == 0 {
		return 0, false
	}
	bp := uintptr(unsafe.Pointer(&b[0]))
	bufp := uintptr(unsafe.Pointer(&buf[0]))
	if bp < bufp {
		return 0, false
	}
	off := int(bp - bufp)
	if off > len(buf) || off+len(b) > len(buf) {
		return 0, false
	}
	return off, true
}

