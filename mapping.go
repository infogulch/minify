// origInterval is a half-open range [start, end) of pristine offsets claimed exact.
type origInterval struct {
	start, end int
}

// findOrigOverlap reports whether [o,end) intersects any claimed interval.
func findOrigOverlap(claimed []origInterval, o, end int) (bool, origInterval) {
	// claimed is sorted by start. Find first with start < end and end > o.
	i := sort.Search(len(claimed), func(i int) bool {
		return claimed[i].end > o
	})
	if i < len(claimed) && claimed[i].start < end {
		return true, claimed[i]
	}
	return false, origInterval{}
}

// addOrigInterval inserts [o,end) into the sorted merged claim list.
func addOrigInterval(claimed []origInterval, o, end int) []origInterval {
	if end <= o {
		return claimed
	}
	i := sort.Search(len(claimed), func(i int) bool {
		return claimed[i].start > o
	})
	// Merge with previous if overlapping or abutting.
	if i > 0 && claimed[i-1].end >= o {
		i--
		if end > claimed[i].end {
			claimed[i].end = end
		}
		if o < claimed[i].start {
			claimed[i].start = o
		}
	} else {
		claimed = append(claimed, origInterval{})
		copy(claimed[i+1:], claimed[i:])
		claimed[i] = origInterval{start: o, end: end}
	}
	// Merge forward while overlapping/abutting.
	for i+1 < len(claimed) && claimed[i].end >= claimed[i+1].start {
		if claimed[i+1].end > claimed[i].end {
			claimed[i].end = claimed[i+1].end
		}
		claimed = append(claimed[:i+1], claimed[i+2:]...)
	}
	return claimed
}

